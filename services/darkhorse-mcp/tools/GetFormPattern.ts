// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export function getFormPattern(input: GetFormPatternInput): GetFormPatternOutput {
  if (!input || typeof input.scenario !== 'string' || input.scenario.trim().length === 0) {
    throw new Error('get_form_pattern: scenario is required (PRINT_FORM | INTERACTIVE_FORM | SMART_FORM).');
  }
  const scenario = input.scenario.trim().toUpperCase() as FormScenario;
  const tpl = TEMPLATES[scenario];
  if (!tpl) {
    throw new Error(`get_form_pattern: unknown scenario "${input.scenario}". Known: ${Object.keys(TEMPLATES).join(', ')}`);
  }
  // Substitute entity hint into the driver template if provided.
  const formName = (input.form_name ?? '').replace(/[^A-Za-z0-9_]+/g, '').slice(0, 30);
  let driverTemplate = tpl.driverTemplate;
  if (formName) {
    driverTemplate = driverTemplate.replace(/ZF_<ENTITY>|ZS_<ENTITY>|<ENTITY>/g, formName);
  }

  return {
    scenario,
    pattern:         tpl.pattern,
    whenToUse:       tpl.whenToUse,
    requiredObjects: tpl.requiredObjects,
    driverTemplate,
    cleanCoreLevel:  tpl.cleanCoreLevel,
    legacyWarning:   tpl.legacyWarning,
    doNotUse:        tpl.doNotUse,
    source:          'embedded',
    catalogVersion:  CATALOG_VERSION
  };
}
