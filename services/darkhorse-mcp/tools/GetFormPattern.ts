/**
 * GetFormPattern — returns the canonical SAP form pattern.
 *
 * Default in S/4HANA: SAP Adobe Forms (FP_FUNCTION_MODULE_NAME). Smart Forms
 * are returned only when explicitly requested with a "legacy, plan migration"
 * notice; SAPscript is not exposed at all (long-deprecated).
 *
 * Form types:
 *   PRINT_FORM        — server-side rendering for print / archive (default)
 *   INTERACTIVE_FORM  — interactive PDF the user fills in and submits
 *   SMART_FORM        — legacy fallback; included with migration warning
 *
 * Required objects for an Adobe form (typical 4-piece stack):
 *   Form Interface  — defines import/export parameters + global data
 *   Form Context    — drives data binding into the layout
 *   Form Layout     — Adobe LiveCycle Designer file (per-instance, not generated by AI)
 *   Driver Program  — looks up FM via FP_FUNCTION_MODULE_NAME and calls it
 */

'use strict';

// ---------------------------------------------------------------------------
// Public types
// ---------------------------------------------------------------------------

export type FormScenario = 'PRINT_FORM' | 'INTERACTIVE_FORM' | 'SMART_FORM';

export interface GetFormPatternInput {
  scenario:   FormScenario | string;
  form_name?: string;       // optional name to substitute into the templates
}

export interface FormObject {
  role:        string;
  type:        string;     // 'FORM_INTERFACE' | 'FORM' | 'PROG' | 'CLAS'
  namingHint:  string;
  notes?:      string;
}

export interface GetFormPatternOutput {
  scenario:        FormScenario;
  pattern:         string;
  whenToUse:       string;
  requiredObjects: FormObject[];
  driverTemplate:  string;             // ABAP driver-program skeleton
  cleanCoreLevel:  'A' | 'B';
  legacyWarning:   string | null;      // populated for SMART_FORM
  doNotUse:        string;             // explicit anti-pattern guidance
  source:          'embedded';
  catalogVersion:  string;
}

// ---------------------------------------------------------------------------
// Pattern library
// ---------------------------------------------------------------------------

const CATALOG_VERSION = '1.0.0';

function adobeDriverTemplate(formName: string): string {
  return [
    `" Driver program for Adobe Form ${formName}`,
    `DATA: lv_fm_name      TYPE rs38l_fnam,`,
    `      ls_outputparams TYPE sfpoutputparams,`,
    `      ls_docparams    TYPE sfpdocparams,`,
    `      ls_formoutput   TYPE fpformoutput.`,
    ``,
    `" 1. Resolve the runtime function module that wraps the form`,
    `CALL FUNCTION 'FP_FUNCTION_MODULE_NAME'`,
    `  EXPORTING  i_name     = '${formName}'`,
    `  IMPORTING  e_funcname = lv_fm_name.`,
    `IF sy-subrc <> 0.`,
    `  RAISE EXCEPTION TYPE zcx_form_not_found.`,
    `ENDIF.`,
    ``,
    `" 2. Open the form processing context`,
    `ls_outputparams-nodialog = abap_true.    " no print dialog for server-side`,
    `ls_outputparams-getpdf   = abap_true.`,
    `CALL FUNCTION 'FP_JOB_OPEN'`,
    `  CHANGING  ie_outputparams = ls_outputparams.`,
    ``,
    `" 3. Call the form FM with the resolved name`,
    `ls_docparams-langu = sy-langu.`,
    `CALL FUNCTION lv_fm_name`,
    `  EXPORTING  /1bcdwb/docparams = ls_docparams`,
    `             i_business_data    = ls_business_data    " your data structure`,
    `  IMPORTING  /1bcdwb/formoutput = ls_formoutput.`,
    ``,
    `" 4. Close the job`,
    `CALL FUNCTION 'FP_JOB_CLOSE'.`,
    ``,
    `" ls_formoutput-pdf contains the rendered PDF bytes for archive / email.`
  ].join('\n');
}

